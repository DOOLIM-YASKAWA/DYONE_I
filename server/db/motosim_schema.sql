-- 나눠 올리기(큰 Cell을 조각으로, 끊기면 이어 올리기). 조각은 <Root>/_tmp/motosim-uploads/<id>.part
create table if not exists motosim.upload_session (
  id              uuid primary key default gen_random_uuid(),
  zone_id         bigint not null references plant.zone(id) on delete cascade,
  project_id      bigint not null references project.project(id),
  file_name       text   not null,
  total_size      bigint not null check (total_size > 0),
  received        bigint not null default 0,
  commit_message  text,
  motosim_version text,
  local_path      text,
  created_by      bigint not null references org.employee(id),
  status          text   not null default 'open' check (status in ('open', 'completed', 'cancelled', 'failed')),
  cell_file_id    bigint references motosim.cell_file(cell_file_id),
  error           text,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);
comment on table motosim.upload_session is 'Cell 나눠 올리기 진행 상태(조각 받은 크기·완료 여부)';

