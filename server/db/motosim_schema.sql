create schema if not exists motosim;
comment on schema motosim is 'DY ONE MotoSim (MotoSim Launcher 이관): Cell 파일 이력, Drive 폴더 매핑, 즐겨찾기, 런처 권한';

-- Cell 파일 업로드 이력. 파일 실물은 Google Drive(고객사/공장/부스/Zone 폴더). Zone마다 최신 1건(is_latest).
create table if not exists motosim.cell_file (
  cell_file_id           bigint generated by default as identity primary key,  -- 원본 id 그대로
  zone_id                bigint not null references plant.zone(id) on delete restrict,
  drive_file_id          text   not null unique,
  drive_file_name        text   not null,
  drive_file_url         text,
  file_size              bigint,
  motosim_version        text,          -- VCL VERSION 15 → 2024, 16 → 2025
  commit_message         text,
  uploaded_by_user_id    text,          -- 원본 런처 사용자 id(사번 형식)
  uploaded_by_name       text,
  uploaded_by_department text,
  uploaded_at            timestamptz not null default now(),
  is_latest              boolean not null default false,
  is_deleted             boolean not null default false,  -- 소프트 삭제(Drive 파일은 휴지통)
  metadata               jsonb   not null default '{}'::jsonb  -- localPath, folderId, folderName, folderUrl, folderSegments
);
comment on table motosim.cell_file is 'MotoSim Cell 파일 업로드 이력 (원본 motosim_launcher.motosim_cell_file)';
create index if not exists cell_file_zone_uploaded_idx on motosim.cell_file (zone_id, uploaded_at desc);
create unique index if not exists cell_file_one_latest_idx on motosim.cell_file (zone_id) where is_latest and not is_deleted;

-- 공정 노드 ↔ Google Drive 폴더. 첫 업로드 때 만들어지고, 이름이 바뀌면 Drive 폴더 이름도 바꾼다.
create table if not exists motosim.drive_folder_map (
  id                     bigint generated by default as identity primary key,
  entity_type            text   not null check (entity_type in ('customer', 'factory', 'booth', 'zone')),
  entity_id              bigint not null,   -- plant.<entity_type>.id
  parent_entity_type     text,
  parent_entity_id       bigint,
  drive_folder_id        text   not null unique,
  drive_folder_name      text   not null,
  parent_drive_folder_id text,
  created_at             timestamptz not null default now(),
  updated_at             timestamptz not null default now(),
  synced_at              timestamptz not null default now(),
  unique (entity_type, entity_id)
);
comment on table motosim.drive_folder_map is '공정 노드 ↔ Google Drive 폴더 매핑 (원본 motosim_drive_folder_map)';

